// Generates the API reference pages from docs/contracts/*.openapi.yaml.
// Runs before `dev` and `build`; the output is git-ignored.
import { readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { generateFiles } from 'fumadocs-openapi';
import { createOpenAPI } from 'fumadocs-openapi/server';
import { parse } from 'yaml';

const contracts = path.join(import.meta.dirname, '..', '..', 'docs', 'contracts');
const out = path.join(import.meta.dirname, '..', 'content', 'docs', 'reference');

const docs = [
  {
    id: 'ledgerbot',
    file: 'ledgerbot.openapi.yaml',
    dir: 'ledgerbot-api',
    title: 'Ledgerbot API',
    description: 'Every endpoint Ledgerbot exposes. Source: docs/contracts/ledgerbot.openapi.yaml.',
  },
  {
    id: 'host',
    file: 'host.openapi.yaml',
    dir: 'host-api',
    title: 'Host contract API',
    description: 'The endpoints Easytrade implements for Ledgerbot. Source: docs/contracts/host.openapi.yaml.',
  },
];

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[^A-Za-z0-9]+/g, '-').toLowerCase();

for (const { id, file, dir, title, description } of docs) {
  const spec = path.join(contracts, file);
  const output = path.join(out, dir);
  await rm(output, { recursive: true, force: true });
  await generateFiles({
    input: createOpenAPI({ input: { [id]: spec } }),
    output,
    per: 'operation',
    groupBy: 'tag',
    includeDescription: true,
    // operationId file names (camelCase) become kebab-case URLs.
    beforeWrite(files) {
      for (const f of files) f.path = f.path.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
    },
  });

  // Sidebar: one folder per tag, in the order the spec declares them, and an index page.
  const { tags = [] } = parse(await readFile(spec, 'utf8'));
  await writeFile(path.join(output, 'meta.json'), JSON.stringify({ title, pages: ['index', ...tags.map((t) => kebab(t.name))] }, null, 2));
  const sections = [];
  for (const t of tags) {
    const folder = kebab(t.name);
    await writeFile(path.join(output, folder, 'meta.json'), JSON.stringify({ title: t.name, description: t.description }, null, 2));
    const cards = [];
    for (const f of (await readdir(path.join(output, folder))).filter((f) => f.endsWith('.mdx')).sort()) {
      const src = await readFile(path.join(output, folder, f), 'utf8');
      const fm = parse(src.split('---')[1]);
      const href = `/docs/reference/${dir}/${folder}/${f.replace(/\.mdx$/, '')}`;
      cards.push(`  <Card title=${JSON.stringify(fm.title)} href="${href}" description=${JSON.stringify(fm._openapi.method)} />`);
    }
    sections.push(`## ${t.name}\n\n${t.description ?? ''}\n\n<Cards>\n${cards.join('\n')}\n</Cards>`);
  }
  await writeFile(
    path.join(output, 'index.mdx'),
    `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---\n\n{/* Generated by scripts/generate-openapi.mjs. */}\n\n${sections.join('\n\n')}\n`,
  );
}
