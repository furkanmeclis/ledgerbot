// T formats a message, falling back to Turkish for missing translations.
func T(lang, key string, args ...any) string {
	f, ok := messages[lang][key]
	if !ok {
		f = messages["tr"][key]
	}
	if len(args) == 0 {
		return f
	}
	return fmt.Sprintf(f, args...)
}
